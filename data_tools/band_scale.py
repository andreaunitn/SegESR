"""
Controlled test of how much generated fine detail the metrics reward.

For a ×s SR output, the LR only holds spatial frequencies below its Nyquist limit, f_c = 1 / (2 s) cycles per HR pixel
(1/8 for ×4): everything above f_c is generated by the model. This script multiplies that part of the spectrum of
every SR image by a factor alpha, with a smooth transition around f_c, and saves the result like an SR output:

  alpha = 0      only the frequencies the LR can support
  alpha = 1      unchanged (sanity check: must give the original metrics)
  alpha > 1      even more generated detail
  --oracle       per image and per octave above f_c ([f_c, 2 f_c) and [2 f_c, Nyquist]), the factor that makes the
                 energy equal to the GT's (needs --gt_dir): what a perfect calibration of the generated detail gives

Scoring the outputs with data_tools/metrics.py and data_tools/fine_structure.py shows which metrics reward
generated detail beyond the GT's amount.

Usage:
    python data_tools/band_scale.py --sr_dir preset/datasets/output/seesr/RealSR \
        --output_dir preset/datasets/output/seesr_hf0.5/RealSR --alpha 0.5
On the cluster: sbatch cluster/band_scale.sh (every alpha, then the metrics).
"""

import argparse
import os

import cv2
import numpy as np

def high_pass(shape, cutoff, width=0.1):
    """Smooth high-pass mask over np.fft.fft2 coefficients: 0 below cutoff * (1 - width), 1 above cutoff * (1 + width),
    raised cosine in between (avoids the ringing of a hard cut)."""

    fy = np.fft.fftfreq(shape[0])[:, None]
    fx = np.fft.fftfreq(shape[1])[None, :]
    f = np.sqrt(fy ** 2 + fx ** 2)
    lo, hi = cutoff * (1 - width), cutoff * (1 + width)
    t = np.clip((f - lo) / (hi - lo), 0.0, 1.0)
    return 0.5 - 0.5 * np.cos(np.pi * t)

def high_energy(image, region):
    """Spectral energy of an (H, W, C) float image over the frequencies where `region` is True, summed over channels."""

    spectrum = np.fft.fft2(image, axes=(0, 1))
    return float((np.abs(spectrum) ** 2)[region].sum())

def full_band(shape, cutoff, width=0.1):
    """Frequencies fully above the transition of `high_pass`, where the scaling is exactly alpha."""

    return high_pass(shape, cutoff, width) >= 1.0

def scale_high_frequencies(image, alpha, cutoff, width=0.1):
    """Multiplies the spectrum of an (H, W, C) image in [0, 1] above `cutoff` by alpha; returns it clipped to [0, 1]."""

    mask = high_pass(image.shape[:2], cutoff, width)
    spectrum = np.fft.fft2(image, axes=(0, 1))
    gain = 1.0 + (alpha - 1.0) * mask
    out = np.real(np.fft.ifft2(spectrum * gain[..., None], axes=(0, 1)))
    return np.clip(out, 0.0, 1.0)

def band_windows(shape, cutoff, width=0.1):
    """Smooth windows of the two octaves above the cutoff, [cutoff, 2 cutoff) and [2 cutoff, Nyquist]; they add up to
    high_pass(cutoff). Returns [(window, core)], core = frequencies where the window is exactly 1."""

    upper = high_pass(shape, 2 * cutoff, width)
    lower = high_pass(shape, cutoff, width) - upper
    return [(lower, lower >= 1.0), (upper, upper >= 1.0)]

def scale_bands(image, gains, cutoff, width=0.1):
    """Multiplies each octave above the cutoff by its gain (see band_windows); returns the image clipped to [0, 1]."""

    spectrum = np.fft.fft2(image, axes=(0, 1))
    gain = np.ones(image.shape[:2])
    for (window, _), g in zip(band_windows(image.shape[:2], cutoff, width), gains):
        gain += (g - 1.0) * window
    out = np.real(np.fft.ifft2(spectrum * gain[..., None], axes=(0, 1)))
    return np.clip(out, 0.0, 1.0)

def oracle_gains(sr, gt, cutoff, width=0.1):
    """Per-octave gains that make the SR energy in each octave above the cutoff equal to the GT's."""

    gains = []
    for _, core in band_windows(sr.shape[:2], cutoff, width):
        sr_energy = high_energy(sr, core)
        gains.append(float(np.sqrt(high_energy(gt, core) / sr_energy)) if sr_energy > 0 else 1.0)
    return gains

def read(path):
    image = cv2.imread(path, cv2.IMREAD_COLOR)
    if image is None:
        raise FileNotFoundError(path)
    return image[..., ::-1].astype(np.float64) / 255.0

def write(path, image):
    cv2.imwrite(path, np.round(image * 255.0).astype(np.uint8)[..., ::-1])

def parse_args(argv=None):
    parser = argparse.ArgumentParser(description="Scale the generated (above the LR Nyquist) frequencies of SR outputs.")
    parser.add_argument("--sr_dir", required=True, help="SR output folder (the sample subfolder is added).")
    parser.add_argument("--output_dir", required=True, help="Results are saved to <output_dir>/<sample>/.")
    parser.add_argument("--sample", default="sample00")
    parser.add_argument("--alpha", type=float, default=None, help="Factor on the frequencies above the cutoff.")
    parser.add_argument("--oracle", action="store_true", help="Per-image alpha matching the GT energy above the cutoff.")
    parser.add_argument("--gt_dir", default=None, help="GT folder, needed by --oracle.")
    parser.add_argument("--scale", type=int, default=4, help="SR factor: the cutoff is 1 / (2 * scale).")
    return parser.parse_args(argv)

def main(argv=None):
    args = parse_args(argv)
    if args.oracle == (args.alpha is not None):
        raise SystemExit("Give exactly one of --alpha and --oracle.")
    if args.oracle and not args.gt_dir:
        raise SystemExit("--oracle needs --gt_dir.")

    cutoff = 1.0 / (2 * args.scale)
    sr_dir = os.path.join(args.sr_dir, args.sample)
    out_dir = os.path.join(args.output_dir, args.sample)
    os.makedirs(out_dir, exist_ok=True)

    names = sorted(name for name in os.listdir(sr_dir) if not name.startswith("."))
    all_gains = []
    for name in names:
        sr = read(os.path.join(sr_dir, name))
        if args.oracle:
            gains = oracle_gains(sr, read(os.path.join(args.gt_dir, name)), cutoff)
            all_gains.append(gains)
            out = scale_bands(sr, gains, cutoff)
        else:
            out = scale_high_frequencies(sr, args.alpha, cutoff)
        write(os.path.join(out_dir, name), out)

    label = "oracle" if args.oracle else f"alpha={args.alpha}"
    print(f"{label}: {len(names)} images from {sr_dir} -> {out_dir} (cutoff {cutoff:.4f} cycles/pixel)")
    if args.oracle:
        for octave, values in zip(("[f_c, 2 f_c)", "[2 f_c, Nyquist]"), np.array(all_gains).T):
            print(f"oracle gain {octave}: mean {values.mean():.3f}, median {np.median(values):.3f}, "
                  f"min {values.min():.3f}, max {values.max():.3f}")

if __name__ == "__main__":
    main()
